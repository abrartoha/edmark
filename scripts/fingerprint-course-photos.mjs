// Renames every course photograph to <slug>.<hash>.jpg and regenerates the
// slug -> filename map the cards read from.
//
// The point is cache busting. Card photos are served with a month-long
// max-age, so a browser that has seen a card keeps that picture until the
// header expires, however many times we replace the file behind it. Putting a
// hash of the contents in the name means replacing a photo changes its URL,
// and a URL nobody has seen cannot be served from anybody's cache.
//
// Safe to run repeatedly: an unchanged photo hashes to the name it already
// has, so a second run is a no-op. Run it after replacing any photo:
//
//   npm run fingerprint:photos

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = "public/images/courses";
const OUT = "lib/course-photos.generated.ts";

/** A fingerprint already applied by an earlier run, e.g. ".3f9a2c18". */
const FINGERPRINT = /\.[0-9a-f]{8}$/;

/** Short enough to keep filenames readable, long enough that two different
 *  photos colliding is not a thing that happens. */
function hash(bytes) {
  return createHash("sha256").update(bytes).digest("hex").slice(0, 8);
}

const files = readdirSync(DIR).filter((f) => f.endsWith(".jpg"));
const map = new Map();
let renamed = 0;

for (const file of files) {
  const stem = file.slice(0, -".jpg".length);
  // Strip any existing fingerprint so re-running rehashes rather than
  // accumulating .aaaaaaaa.bbbbbbbb on the end.
  const slug = stem.replace(FINGERPRINT, "");
  const wanted = `${slug}.${hash(readFileSync(join(DIR, file)))}.jpg`;

  if (file !== wanted) {
    renameSync(join(DIR, file), join(DIR, wanted));
    renamed++;
  }

  if (map.has(slug)) {
    throw new Error(`Two files claim the slug "${slug}": ${map.get(slug)} and ${wanted}`);
  }
  map.set(slug, wanted);
}

const entries = [...map].sort(([a], [b]) => a.localeCompare(b));

writeFileSync(
  OUT,
  `// Generated by scripts/fingerprint-course-photos.mjs. Do not edit by hand.
// Run \`npm run fingerprint:photos\` after adding or replacing a course photo.

/** Course slug to the fingerprinted filename under /images/courses. */
export const COURSE_PHOTO_FILES: Record<string, string> = {
${entries.map(([slug, file]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(file)},`).join("\n")}
};
`
);

console.log(`${entries.length} photos, ${renamed} renamed -> ${OUT}`);
